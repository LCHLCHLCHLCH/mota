        -- 逃亡高级巫师(136)：玩家在其正下方时上移一格，直到 (1,2) 才停下
        for y = 2, 9 do
            if get_tile(1, y) == 136 then
                if player_x() == 1 and player_y() == y + 1 and y > 2 then
                    set_tile(1, y, 1)
